from backend.jobs.queue import JobQueue


@pytest.fixture
def isolated_client(tmp_path):
    db_file = tmp_path / "test_ext_jobs.db"
    config_file = tmp_path / "test_ext_config.json"
    test_queue = JobQueue(db_path=db_file)
    test_config_mgr = ConfigManager(config_path=config_file)

    with TestClient(app) as client:
        app.state.queue = test_queue
        app.state.config_mgr = test_config_mgr
        yield client


def test_extension_manifest_exists_and_valid():
    manifest_path = Path("extension/manifest.json")
    assert manifest_path.exists()

    content = json.loads(manifest_path.read_text(encoding="utf-8"))
    assert content.get("manifest_version") == 3
    assert content.get("name") == "GhostPush — AI Code Repository Sync"
    assert "http://127.0.0.1:8000/*" in content.get("host_permissions", [])


def test_extension_files_exist():
    ext_dir = Path("extension")
    assert (ext_dir / "manifest.json").exists()
    assert (ext_dir / "popup.html").exists()
    assert (ext_dir / "popup.js").exists()
    assert (ext_dir / "content.js").exists()
    assert (ext_dir / "background.js").exists()
    assert (ext_dir / "styles.css").exists()


def test_extension_payload_compatibility_with_backend_job_api(isolated_client):
    # Payload format generated by extension popup.js
    ext_payload = {
        "api_version": "1.0",
        "job_id": "JOB-EXT-1723400000-1234",
        "platform": "leetcode",
        "problem": {
            "title": "Two Sum",
            "difficulty": "Easy",
            "url": "https://leetcode.com/problems/two-sum/",
            "tags": ["Array", "Hash Table"]
        },
        "solution": {
            "language": "python",
            "code": "class Solution:\n    def twoSum(self, nums, target):\n        pass"
        },
        "repository_path": "/tmp/test_repo"
    }

    # Verify Pydantic validation
    payload_obj = SubmissionPayload.model_validate(ext_payload)
    assert payload_obj.job_id == "JOB-EXT-1723400000-1234"
    assert payload_obj.platform == "leetcode"
    assert payload_obj.problem.title == "Two Sum"

    # Verify POST /api/v1/jobs endpoint accepts extension payload
    response = isolated_client.post("/api/v1/jobs", json=ext_payload)
    assert response.status_code == 201

    data = response.json()
    assert data["job_id"] == "JOB-EXT-1723400000-1234"
    assert data["status"] == "QUEUED"
